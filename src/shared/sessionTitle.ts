// 会话标题的显示兜底（issue #925）。
//
// 标题是第一条 user_message 首行的投影（日志推导，不是一个可编辑字段的默认值），
// 所以「还没发过话的会话」天然没有标题：刚从侧栏 ＋ 建出来的、开局卡上还没打字的、
// 云端刚落库那条。这些在清单里长成**一格空白**——比什么都不显示更糟：一行看不出
// 是什么，也看不出能不能点，真机上就是一条灰条（#925 的截图）。
//
// 兜底统一成「新会话」，而不是各处各给一个（原来是文件夹名 / 「任务」 / 会话 id）：
// 它和用户刚才按的那颗钮是同一个词，读起来就是「这是我刚开的那条，还没说话」。
// 各处不同的兜底还有一个隐藏代价——同一条会话在侧栏叫文件夹名、在 ⌘K 里叫另一个
// 名字，人得先意识到「这两行是同一条」。
//
// 判据 trim 之后比空串，不是 `?? `：`""` 和 `"   "` 在界面上是同一件事（一格空白），
// 而 `??` 只挡得住 null——云会话那张表的 title 是 `string`，落库时就是空串。

/** 没有标题的会话在清单里显示成什么。侧栏那颗按钮上写的也是这四个字 */
export const UNTITLED_SESSION_TITLE = "新会话";

/** 清单里那一格显示什么：有标题用标题，空白（null / "" / 全是空格）用兜底 */
export function displaySessionTitle(title: string | null | undefined): string {
  const trimmed = (title ?? "").trim();
  return trimmed === "" ? UNTITLED_SESSION_TITLE : trimmed;
}
